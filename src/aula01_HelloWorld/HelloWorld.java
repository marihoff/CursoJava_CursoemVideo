/**
 * Aula 01 - Primeiro Programa em Java
 *
 * Conceitos abordados:
 * - Estrutura básica de uma classe Java
 * - Método main (ponto de entrada do programa)
 * - System.out.println para imprimir no console
 * - Comentários de linha (//) e de bloco (/* )
 */
public class HelloWorld {

    public static void main(String[] args) {

        // Imprime uma mensagem no console
        System.out.println("Olá, mundo!");
        System.out.println("Bem-vindo ao Java!");

        /*
         * Este é um comentário de bloco.
         * Pode ocupar várias linhas.
         */

        /**
         * Este é um comentário de documentação (Javadoc).
         * Usado para documentar classes e métodos.
         */

        System.out.println("Meu primeiro programa em Java está funcionando!");
    }
}
